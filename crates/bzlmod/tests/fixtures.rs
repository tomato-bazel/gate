//! Hermetic tests over real `MODULE.bazel` files vendored from the registry.
//!
//! The whole-registry sweep in `corpus.rs` needs a checkout on disk, so under
//! Bazel it skips. These fixtures are `include_str!`d, which makes them
//! compile-time inputs — identical behaviour under `cargo test` and
//! `bazel test`, no runfiles lookup, no sandbox escape.
//!
//! Each fixture is here because it exercises a path the gates depend on. When
//! one of these modules is remediated upstream the fixture does **not** get
//! refreshed — it is pinned evidence of the shape the gate must catch.

const D3_AFTER: &str = include_str!("../testdata/d3_after.MODULE.bazel");
const D3_LIVE_VIOLATION: &str = include_str!("../testdata/d3_live_violation.MODULE.bazel");
const FOREIGN_EXT_NAMESPACED: &str =
    include_str!("../testdata/foreign_ext_namespaced.MODULE.bazel");
const S4_LOCAL_PATH_OVERRIDE: &str =
    include_str!("../testdata/s4_local_path_override.MODULE.bazel");
const DEV_DEPS_AND_TOOLCHAINS: &str =
    include_str!("../testdata/dev_deps_and_toolchains.MODULE.bazel");
const COMPLEX: &str = include_str!("../testdata/complex.MODULE.bazel");

fn parse(name: &str, text: &str) -> bzlmod::ModuleFile {
    bzlmod::parse(name, text).unwrap_or_else(|e| panic!("{name}: {e}"))
}

#[test]
fn every_fixture_parses() {
    for (name, text) in [
        ("d3_after", D3_AFTER),
        ("d3_live_violation", D3_LIVE_VIOLATION),
        ("foreign_ext_namespaced", FOREIGN_EXT_NAMESPACED),
        ("s4_local_path_override", S4_LOCAL_PATH_OVERRIDE),
        ("dev_deps_and_toolchains", DEV_DEPS_AND_TOOLCHAINS),
        ("complex", COMPLEX),
    ] {
        let f = parse(name, text);
        assert!(f.module.is_some(), "{name}: no module() declaration");
    }
}

#[test]
fn rules_k8s_shipped_the_d3_fix() {
    // 0.0.3 is the version that followed the "a repo named
    // distroless_static_linux_amd64 is already generated by this module
    // extension" break. Its oci.pull names are prefixed with the module name.
    let f = parse("rules_k8s", D3_AFTER);
    assert!(
        f.unnamespaced_extension_repos().is_empty(),
        "rules_k8s 0.0.3 should be clean, got {:?}",
        f.unnamespaced_extension_repos()
    );
    assert!(f
        .apparent_repo_names()
        .any(|r| r == "rules_k8s_distroless_static"));
}

#[test]
fn rules_k8s_keeps_rules_go_as_a_runtime_dep() {
    // The post-mortem in this file: rules_go had to STOP being a
    // dev_dependency because `//crd/private/crd_library.bzl` loads an aspect
    // from it at rule-definition time, and a dev dep is invisible to
    // consumers. D1 must agree that this is a runtime dep.
    let f = parse("rules_k8s", D3_AFTER);
    assert!(
        f.runtime_deps().any(|d| d.name == "rules_go"),
        "rules_go must be a runtime dep"
    );
    assert!(!f.dev_deps().any(|d| d.name == "rules_go"));
}

#[test]
fn vpn_still_has_the_live_d3_violation() {
    // Same extension and same class as the rules_k8s bug, unfixed: an
    // unnamespaced oci.pull on the shared @rules_oci extension.
    let f = parse("vpn", D3_LIVE_VIOLATION);
    let found = f.unnamespaced_extension_repos();
    assert!(
        found
            .iter()
            .any(|(ext, repo)| *repo == "distroless_java" && ext.starts_with("@rules_oci")),
        "expected the distroless_java violation, got {found:?}"
    );
}

#[test]
fn rules_jena_is_a_declared_toolchain_provider() {
    // Four non-dev toolchain registrations, which is correct here: being a
    // toolchain implementation is the module's entire purpose. D2 must key on
    // *undeclared* leakage, not on any registration, or it condemns this.
    let f = parse("rules_jena", FOREIGN_EXT_NAMESPACED);
    let leaking: Vec<&str> = f.leaking_toolchains().collect();
    assert_eq!(leaking.len(), 4, "got {leaking:?}");
    assert!(leaking.iter().all(|l| l.contains("jena")));
}

#[test]
fn rules_jena_namespaces_its_maven_install() {
    // `maven.install(name = "jena_maven")` on the shared @rules_jvm_external
    // extension — the correct pattern, and the reason is_namespaced_by accepts
    // a dropped `rules_` prefix.
    let f = parse("rules_jena", FOREIGN_EXT_NAMESPACED);
    assert!(f.unnamespaced_extension_repos().is_empty());
    assert!(f.apparent_repo_names().any(|r| r == "jena_maven"));
}

#[test]
fn rules_schema_org_carries_local_path_overrides() {
    // S4: overrides are honoured only in the root module, so these do nothing
    // for consumers — and their presence means the module was published from a
    // workspace where those deps resolved locally, i.e. it may never have been
    // built against the registry versions it declares.
    let f = parse("rules_schema_org", S4_LOCAL_PATH_OVERRIDE);
    let overrides: Vec<&str> = f.overrides.iter().map(|o| o.module_name()).collect();
    assert!(overrides.contains(&"rules_rdf"), "got {overrides:?}");
    assert!(f
        .overrides
        .iter()
        .all(|o| o.directive() == "local_path_override"));
}

#[test]
fn rules_lean_scopes_its_smoke_toolchain_to_dev() {
    // The counterexample to the D2 corpus finding: rules_lean registers a Lean
    // toolchain for its own integration test under dev_dependency = True, so
    // it does not reach consumers. This is the shape D2 asks others to adopt.
    let f = parse("rules_lean", DEV_DEPS_AND_TOOLCHAINS);
    assert!(
        f.leaking_toolchains().next().is_none(),
        "rules_lean should leak no toolchains, got {:?}",
        f.leaking_toolchains().collect::<Vec<_>>()
    );
    assert!(!f.toolchains.is_empty(), "but it does register one");
    assert!(f.dev_deps().any(|d| d.name == "stardoc"));
}

#[test]
fn the_most_complex_module_round_trips() {
    // meridian is the widest file in the registry — many extensions, tags,
    // use_repo calls and toolchain registrations. Mostly a canary for the
    // evaluator.
    let f = parse("meridian", COMPLEX);
    assert!(f.extensions.len() >= 3, "extensions: {}", f.extensions.len());
    assert!(f.deps.len() >= 10, "deps: {}", f.deps.len());
    assert!(f.extensions.iter().any(|e| !e.tags.is_empty()));
    assert!(f.apparent_repo_names().count() > 0);
}
